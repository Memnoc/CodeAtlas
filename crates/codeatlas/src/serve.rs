//! `codeatlas serve`: the embedded dashboard over loopback (ticket 09).
//!
//! The server is a hand-rolled HTTP/1.1 responder on `std::net::TcpListener`
//! rather than a server crate: it needs exactly one verb (GET), three routes,
//! and zero TLS/streaming/routing machinery, so even the smallest server
//! dependency (tiny_http and its transitive tree) would be more code than
//! this file. Under ADR-0006 the serve path must survive a security audit by
//! reading it — a screenful of std with one hardcoded loopback bind is the
//! strongest form of that argument.
//!
//! Runtime I/O is exactly: one listening socket on 127.0.0.1, asset bytes
//! from process memory, the map from local disk. Nothing else, ever.

use std::io::{BufRead, BufReader, Write};
use std::net::{Ipv4Addr, TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::thread;

use anyhow::{Context, Result, bail};

use crate::scan::OUTPUT_DIR;

// Generated by build.rs: `ASSETS`, the dashboard production build keyed by
// URL path with precomputed MIME types.
include!(concat!(env!("OUT_DIR"), "/embedded_assets.rs"));

/// Serves the embedded dashboard and `<root>/.codeatlas/knowledge-graph.json`
/// on 127.0.0.1 until the process is interrupted. Loopback is hardcoded — the
/// listener cannot be pointed at a routable interface (ADR-0006). Port 0 asks
/// the OS for a free port; the actually bound URL is printed to stdout.
pub fn serve(root: &Path, port: u16) -> Result<()> {
    let root = root
        .canonicalize()
        .with_context(|| format!("cannot serve {}", root.display()))?;
    let map_path = root.join(OUTPUT_DIR).join("knowledge-graph.json");
    if !map_path.exists() {
        bail!(
            "no map at {} — run `codeatlas scan {}` first",
            map_path.display(),
            root.display()
        );
    }

    let listener = TcpListener::bind((Ipv4Addr::LOCALHOST, port)).with_context(|| {
        format!("cannot bind 127.0.0.1:{port} — is the port in use? (--port picks another; 0 lets the OS choose)")
    })?;
    let addr = listener.local_addr()?;
    // The URL goes to stdout so scripts (and the e2e test) can capture it;
    // stdout is line-buffered, so the line is visible before we block.
    println!("CodeAtlas dashboard at http://{addr}/");
    eprintln!("serving {} — press Ctrl-C to stop", root.display());

    // Ctrl-C ends the process (default SIGINT handling); nothing to clean up
    // beyond what the OS reclaims. One thread per connection: browsers open
    // parallel connections for assets, and blocking them behind one another
    // stalls first paint.
    for stream in listener.incoming() {
        let Ok(stream) = stream else { continue };
        let map_path = map_path.clone();
        thread::spawn(move || {
            // Per-connection errors (client hung up mid-request) only affect
            // that client; the server must outlive them.
            let _ = handle(stream, &map_path);
        });
    }
    Ok(())
}

/// Answers one request and closes the connection (`Connection: close` — the
/// dashboard is a handful of requests, keep-alive buys nothing but state).
fn handle(stream: TcpStream, map_path: &PathBuf) -> std::io::Result<()> {
    let mut reader = BufReader::new(stream);
    let mut request_line = String::new();
    reader.read_line(&mut request_line)?;
    // Drain the headers; nothing in them changes how we respond.
    loop {
        let mut line = String::new();
        if reader.read_line(&mut line)? == 0 || line == "\r\n" || line == "\n" {
            break;
        }
    }
    let mut stream = reader.into_inner();

    let mut parts = request_line.split_whitespace();
    let (method, target) = match (parts.next(), parts.next()) {
        (Some(m), Some(t)) => (m, t),
        _ => return respond(&mut stream, "400 Bad Request", "text/plain", b"bad request"),
    };
    if method != "GET" {
        return respond(
            &mut stream,
            "405 Method Not Allowed",
            "text/plain",
            b"only GET is served",
        );
    }
    let path = target.split(['?', '#']).next().unwrap_or(target);

    if path == "/api/map" {
        // Read from disk per request so a re-scan shows up on refresh.
        return match std::fs::read(map_path) {
            Ok(map) => respond(&mut stream, "200 OK", "application/json", &map),
            Err(_) => respond(
                &mut stream,
                "404 Not Found",
                "application/json",
                format!(
                    "{{\"error\":\"no map at {} — run `codeatlas scan` first\"}}",
                    map_path.display()
                )
                .as_bytes(),
            ),
        };
    }

    let asset_path = match path.trim_start_matches('/') {
        "" => "index.html",
        rest => rest,
    };
    match ASSETS.iter().find(|a| a.path == asset_path) {
        Some(asset) => respond(&mut stream, "200 OK", asset.content_type, asset.bytes),
        None => respond(&mut stream, "404 Not Found", "text/plain", b"not found"),
    }
}

fn respond(
    stream: &mut TcpStream,
    status: &str,
    content_type: &str,
    body: &[u8],
) -> std::io::Result<()> {
    write!(
        stream,
        "HTTP/1.1 {status}\r\nContent-Type: {content_type}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
        body.len()
    )?;
    stream.write_all(body)?;
    stream.flush()
}
